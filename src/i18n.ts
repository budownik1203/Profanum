/**
 * Every text the player reads, in Polish and English (design doc: Języki).
 * `t("key", { n: 3 })` replaces {n}. Missing English falls back to Polish, missing Polish to the key.
 */
export type Lang = "pl" | "en";

let LANG: Lang = "pl";
export const setLang = (l: Lang): void => {
  LANG = l;
};
export const lang = (): Lang => LANG;

export function t(key: string, vars: Record<string, string | number> = {}): string {
  const s = (LANG === "en" ? EN[key] : undefined) ?? PL[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k: string) => (k in vars ? String(vars[k]) : `{${k}}`));
}

/** Polish plural: 1 dusza, 2-4 dusze, 5+ dusz. */
export function plural(n: number, one: string, few: string, many: string): string {
  if (LANG === "en") return n === 1 ? one : few;
  if (n === 1) return one;
  const last = n % 10;
  const lastTwo = n % 100;
  return last >= 2 && last <= 4 && (lastTwo < 12 || lastTwo > 14) ? few : many;
}

/** Whether a language has its own text for a key (tests: nothing left untranslated). */
export const hasText = (key: string, l: Lang): boolean => key in (l === "en" ? EN : PL);
export const textKeys = (l: Lang): string[] => Object.keys(l === "en" ? EN : PL);

export const soulsWord = (n: number): string => (LANG === "en" ? (n === 1 ? "soul" : "souls") : plural(n, "dusza", "dusze", "dusz"));

